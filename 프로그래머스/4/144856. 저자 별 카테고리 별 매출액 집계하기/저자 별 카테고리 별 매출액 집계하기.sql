-- 2022년 1월의 도서 판매 데이터를 기준으로 저자 별, 카테고리 별 매출액(TOTAL_SALES = 판매량 * 판매가) 을 구하여, 저자 ID(AUTHOR_ID), 저자명(AUTHOR_NAME), 카테고리(CATEGORY), 매출액(SALES) 리스트를 출력하는 SQL문을 작성해주세요.

SELECT
    C.AUTHOR_ID,
    C.AUTHOR_NAME,
    B.CATEGORY,
    SUM(A.SALES * B.PRICE) AS TOTAL_SALES
FROM BOOK_SALES A
JOIN BOOK B ON A.BOOK_ID = B.BOOK_ID
JOIN AUTHOR C ON B.AUTHOR_ID = C.AUTHOR_ID
WHERE A.SALES_DATE >= '2022-01-01' AND A.SALES_DATE < '2022-02-01'
GROUP BY 
    C.AUTHOR_ID,
    C.AUTHOR_NAME,
    B.CATEGORY
ORDER BY C.AUTHOR_ID ASC, B.CATEGORY DESC;