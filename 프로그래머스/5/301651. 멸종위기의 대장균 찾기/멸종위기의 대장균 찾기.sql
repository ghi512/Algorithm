WITH RECURSIVE GEN AS (
    -- 부모가 없는 개체 = 1세대
    SELECT
        ID,
        1 AS GENERATION
    FROM ECOLI_DATA
    WHERE PARENT_ID IS NULL
    
    UNION ALL
    
    -- GEN에 있는 개체의 자식 = 부모세대 + 1
    SELECT A.ID, B.GENERATION + 1
    FROM ECOLI_DATA A
    JOIN GEN B ON A.PARENT_ID = B.ID
)

SELECT
    COUNT(*) AS COUNT,
    A.GENERATION
FROM GEN A
LEFT JOIN ECOLI_DATA B ON A.ID = B.PARENT_ID
WHERE B.ID IS NULL
GROUP BY A.GENERATION
ORDER BY A.GENERATION ASC;